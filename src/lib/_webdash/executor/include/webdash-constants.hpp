/**
 * WebDash Constants
 * =================
 *
 * Single source of truth for all WebDash magic strings and constants.
 *
 * Organization:
 *   - WebDashConst::Public    — Public API: filenames, env vars (safe for external use)
 *   - WebDashConst::Internal  — Implementation details: validation keys (internal only)
 *
 * Usage in C++:
 *   #include <webdash-constants.hpp>
 *   auto filename = WebDashConst::Public::kRootProfileFilename;
 *
 * Usage in shell scripts (setup-webdash.sh extracts these via grep):
 *   PROFILE_FILENAME=$(grep -oP 'kRootProfileFilename\[\] = "\K[^"]+' webdash-constants.hpp)
 */

#pragma once

#include <cstddef>

namespace WebDashConst {

/**
 * Public constants - safe for external code and scripts to reference.
 */
namespace Public {

    // =========================================================================
    // Environment
    // =========================================================================

    /// Environment variable name that stores the path to WebDash root directory.
    /// Used by: shell init scripts, CMake builds, runtime lookups.
    constexpr char kEnvVarName[] = "WEBDASH";


    // =========================================================================
    // Filenames
    // =========================================================================

    /// Root profile JSONC that defines environment, paths, and projects.
    /// Located at: $WEBDASH/webdash.profile.jsonc
    constexpr char kRootProfileFilename[] = "webdash.profile.jsonc";

    /// Shell initialization script that users source in ~/.bashrc.
    /// Generated by webdash client with PATH and environment exports.
    /// Located at: $WEBDASH/app-persistent/data/webdash-client/webdash.terminal.init.sh
    constexpr char kTerminalInitFilename[] = "webdash.terminal.init.sh";

    /// Per-project config JSONC that defines commands and tasks.
    /// Located at: <project>/webdash.config.jsonc
    constexpr char kProjectConfigFilename[] = "webdash.config.jsonc";


    // =========================================================================
    // Directory Names
    // =========================================================================

    /// Persistent storage directory (survives updates).
    constexpr char kPersistentStorageDir[] = "app-persistent";

    /// Temporary storage directory (may be cleared).
    constexpr char kTemporaryStorageDir[] = "app-temporary";

    /// Logging subdirectory within temporary storage.
    constexpr char kLoggingSubdir[] = "logging";


    // =========================================================================
    // Logging
    // =========================================================================

    /// Maximum log file size in bytes before rotation (10 MB).
    constexpr std::size_t kMaxLogFileSizeBytes = 10 * 1024 * 1024;

    /// Prefix for rotated log files.
    constexpr char kLogRotationPrefix[] = "previous.";

    /// Log filename prefix.
    constexpr char kLogFilenamePrefix[] = "logging.";


    // =========================================================================
    // Task Names
    // =========================================================================

    /// Default task name when none is specified.
    constexpr char kDefaultTaskName[] = "all";


    // =========================================================================
    // Substitution Keywords
    // =========================================================================

    /// Keyword for root directory substitution in configs.
    constexpr char kSubstRootDir[] = "$.rootDir()";

    /// Keyword for current config's directory substitution.
    constexpr char kSubstThisDir[] = "$.thisDir()";

    /// Keyword for config-scoped temporary directory substitution.
    /// Expands to: <root>/app-temporary/<scope>, where <scope> is derived from
    ///             src/(bin|static|lib)/<first-child>.
    constexpr char kSubstWebDashTemporary[] = "$.webdash.temporary()";

    /// Keyword for config-scoped persistent directory substitution.
    /// Expands to: <root>/app-persistent/<scope>, where <scope> is derived from
    ///             src/(bin|static|lib)/<first-child>.
    constexpr char kSubstWebDashPersistent[] = "$.webdash.persistent()";

    /// Keyword for command-line arguments substitution.
    constexpr char kSubstArgs[] = "$.args()";


    // =========================================================================
    // Profile JSON Keys
    // =========================================================================

    /// Key for external modules array in webdash.profile.jsonc.
    /// Modules are WebDash projects with webdash.config.jsonc that can be built/run.
    /// Example:
    ///   "modules": [
    ///       { "path": "$.rootDir()/src/bin/my-tool", "git": "git@github.com:user/repo.git", "run": ":build" }
    ///   ]
    constexpr char kProfileKeyModules[] = "modules";

    /// Key for external dependencies array in webdash.profile.jsonc.
    /// Dependencies are external git repos that just need to be cloned (no WebDash tasks).
    /// Example:
    ///   "dependencies": [
    ///       { "path": "$.rootDir()/src/lib/external/json", "git": "git@github.com:nlohmann/json.git" }
    ///   ]
    constexpr char kProfileKeyDependencies[] = "dependencies";

    /// Module/dependency entry fields (shared).
    constexpr char kModuleFieldPath[] = "path";
    constexpr char kModuleFieldGit[] = "git";
    constexpr char kModuleFieldBranch[] = "branch";
    constexpr char kModuleFieldRun[] = "run";
    constexpr char kModuleFieldAutoRegister[] = "register";
    constexpr char kModuleFieldAction[] = "action";    // Single action command (alternative to actions array)
    constexpr char kModuleFieldActions[] = "actions";  // WebDash task to run for setup (alternative to git)
    constexpr char kModuleFieldWdir[] = "wdir";        // Working directory for actions (supports $.path())
    constexpr char kModuleFieldProjectLocation[] = "project-location";  // Path where project declares it should be installed
    constexpr char kModuleFieldBundle[] = "bundle";    // Array of git URLs to batch multiple simple git-only modules


    // =========================================================================
    // Task Config Fields
    // =========================================================================

    /// If true, suppress verbose output for this task.
    constexpr char kTaskFieldSilent[] = "silent";

    /// Test case description - when present, prints [PASS] or [FAIL] with this message.
    constexpr char kTaskFieldTestCase[] = "test-case";


    // =========================================================================
    // Config-Level Fields
    // =========================================================================

    /// If true, the project directory is served over HTTP by the static file server.
    /// All files in the config's directory (and subdirectories) become accessible.
    constexpr char kConfigFieldNetworkShared[] = "network-shared";

    /// Optional identifier used for widget/static storage naming.
    /// Example: "webdash-widget-music-player"
    constexpr char kConfigFieldWidgetIdentifier[] = "widget-identifier";

    /// Optional override for the directory served by the static file server.
    /// If set, this directory is served instead of the config's own directory.
    /// Supports WebDash variable substitution (e.g., $.rootDir(), $.thisDir()).
    constexpr char kConfigFieldNetworkSharedSourceDir[] = "network-shared-sourcedir";


    // =========================================================================
    // Profile Port Keys
    // =========================================================================

    /// Port key for the built-in static file server in webdash.profile.jsonc "ports".
    constexpr char kProfilePortStaticFileServer[] = "static-file-server";

    /// Default port for the built-in static file server (portal, widget pop-outs,
    /// network-shared serving) when the profile doesn't specify
    /// `ports.static-file-server`. This is core WebDash infrastructure, not a
    /// user project port, so it works out of the box without requiring every
    /// profile to define it - `ports.static-file-server` in the profile can
    /// still override it (e.g., to avoid a conflict with something else on
    /// the machine), or disable it entirely by setting it to "0".
    constexpr int kDefaultStaticFileServerPort = 8780;


    // =========================================================================
    // Profile Settings Keys
    // =========================================================================

    /// Key for settings object in webdash.profile.jsonc.
    constexpr char kProfileKeySettings[] = "settings";

    /// Whether to prompt user before auto-cloning modules (default: false).
    /// Example in webdash.profile.jsonc:
    ///   "settings": {
    ///       "interactive-clone": true
    ///   }
    constexpr char kSettingsInteractiveClone[] = "interactive-clone";

} // namespace Public


/**
 * Internal constants - implementation details, not part of public API.
 */
namespace Internal {

    // =========================================================================
    // Profile Validation
    // =========================================================================

    /// Magic key that must exist in profile JSON to identify it as WebDash root.
    /// The profile is valid if it contains: { "webdash": { "rootDir": "this" } }
    /// which flattens to the key-value pair below.
    constexpr char kMagicProfileKey[] = "$#.webdash.rootDir";
    constexpr char kMagicProfileValue[] = "this";

    /// Human-readable version of the magic key for error messages.
    constexpr char kMagicProfileKeyHumanReadable[] = "webdash.rootDir";


    // =========================================================================
    // JSON Parsing
    // =========================================================================

    /// Prefix used to identify WebDash JSON keys (flattened key notation).
    constexpr char kJsonKeyPrefix[] = "$#";

    /// String representations of JSON boolean values.
    constexpr char kJsonBoolTrue[] = "true";
    constexpr char kJsonBoolFalse[] = "false";

} // namespace Internal

} // namespace WebDashConst
